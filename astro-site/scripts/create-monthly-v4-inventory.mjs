const inventory = {};
for (const file of (await fs.readdir(digestDir)).filter((name) => name.endsWith('.json'))) {
  const order = Number(file.split('-')[0]);
  const digest = JSON.parse(await fs.readFile(path.join(digestDir, file), 'utf8'));
  inventory[order] = (exact[order] ?? digest.updates.map((item) => {
    const description = clean(item.description);
    const invalidModule = !item.module || item.module === '未标注';
    const semanticModule = inferModule(description);
    const useSemanticModule = invalidModule || (semanticModule !== '系统' && semanticModule !== item.module);
    return {
      module: useSemanticModule ? semanticModule : item.module,
      moduleSource: useSemanticModule ? 'inferred' : (String(item.moduleSource).startsWith('explicit') ? item.moduleSource : 'inferred'),
      type: item.type,
      typeSource: item.typeSource,
      sourceText: item.description,
      description,
    };
  })).map((item, index) => ({ id: `review-${String(index + 1).padStart(2, '0')}`, ...item }));
}

// Ensure all exact items are included even if digest does not exist yet
for (const [orderStr, items] of Object.entries(exact)) {
  const order = Number(orderStr);
  if (!inventory[order]) {
    inventory[order] = items.map((item, index) => ({ id: `review-${String(index + 1).padStart(2, '0')}`, ...item }));
  }
}

await fs.writeFile(output, `${JSON.stringify({ reviewVersion: 4, articles: inventory }, null, 2)}\n`);
console.log(`Created V4 reviewed update inventory: ${Object.keys(inventory).length} articles.`);
